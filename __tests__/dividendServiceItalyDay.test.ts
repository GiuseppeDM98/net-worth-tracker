/**
 * dividendService — the day of an ex-date is the ITALIAN one (2026-11-24).
 *
 * A coupon reached Firestore at two instants for one day: the cron at Italian midnight (23:00 UTC of the
 * day before), the asset form at UTC midnight. The duplicate check read the process zone's day — UTC on
 * Vercel — and the deterministic id the UTC date, so the cron found nothing and wrote the coupon a second
 * time under another id. Held under TZ=UTC and TZ=Europe/Rome alike.
 */
import { beforeEach, describe, expect, it, vi } from 'vitest';

vi.mock('server-only', () => ({}));

const { whereCalls, docIds, querySize, queryDocs, batchDeletes } = vi.hoisted(() => ({
  whereCalls: [] as Array<[string, string, unknown]>,
  docIds: [] as string[],
  querySize: { current: 0 },
  queryDocs: { current: [] as Array<{ ref: string; data: () => Record<string, unknown> }> },
  batchDeletes: [] as string[],
}));

vi.mock('@/lib/firebase/admin', () => {
  const query = {
    where: (field: string, op: string, value: unknown) => {
      whereCalls.push([field, op, value]);
      return query;
    },
    get: async () => ({ empty: querySize.current === 0 && queryDocs.current.length === 0, size: querySize.current, docs: queryDocs.current }),
  };
  return {
    adminDb: {
      batch: () => ({ delete: (ref: string) => { batchDeletes.push(ref); }, commit: async () => undefined }),
      collection: () => ({
        ...query,
        doc: (id: string) => ({ set: async () => { docIds.push(id); } }),
      }),
    },
  };
});

import { createDividend, deleteUpcomingCouponsForAsset, isDuplicateDividend } from '@/lib/services/dividendService';

const ITALIAN_MIDNIGHT = new Date('2026-12-14T23:00:00.000Z'); // 15/12/2026 00:00 in Italy
const UTC_MIDNIGHT = new Date('2026-12-15T00:00:00.000Z'); // 15/12/2026 01:00 in Italy

const millisOf = (value: unknown) => (value as { toMillis: () => number }).toMillis();

describe('the Italian day of an ex-date', () => {
  beforeEach(() => {
    whereCalls.length = 0;
    docIds.length = 0;
    querySize.current = 0;
    queryDocs.current = [];
    batchDeletes.length = 0;
    vi.useRealTimers();
  });

  it('cleans the upcoming coupons from the start of the Italian day, never a cashed one', async () => {
    vi.useFakeTimers();
    vi.setSystemTime(new Date('2026-12-15T10:00:00.000Z')); // 11:00 in Italy, the payment day
    queryDocs.current = [
      { ref: 'cashed-today', data: () => ({ expenseId: 'exp-1' }) },
      { ref: 'pending-next', data: () => ({}) },
    ];
    await deleteUpcomingCouponsForAsset('u1', 'a1');
    vi.useRealTimers();
    const from = millisOf(whereCalls.find(([f, op]) => f === 'paymentDate' && op === '>=')![2]);
    expect(from).toBeLessThanOrEqual(ITALIAN_MIDNIGHT.getTime());
    expect(batchDeletes).toEqual(['pending-next']);
  });

  it('looks for a duplicate across the whole Italian day, both instants inside it', async () => {
    await isDuplicateDividend('u1', 'a1', ITALIAN_MIDNIGHT);
    const from = millisOf(whereCalls.find(([f, op]) => f === 'exDate' && op === '>=')![2]);
    const to = millisOf(whereCalls.find(([f, op]) => f === 'exDate' && op === '<=')![2]);
    for (const instant of [ITALIAN_MIDNIGHT, UTC_MIDNIGHT]) {
      expect(instant.getTime()).toBeGreaterThanOrEqual(from);
      expect(instant.getTime()).toBeLessThanOrEqual(to);
    }
  });

  it('gives an automatic coupon one id whichever instant of its day it carries', async () => {
    for (const exDate of [ITALIAN_MIDNIGHT, UTC_MIDNIGHT]) {
      await createDividend('u1', {
        assetId: 'a1', exDate, paymentDate: exDate, dividendPerShare: 1, quantity: 10, grossAmount: 10,
        taxAmount: 1.25, netAmount: 8.75, currency: 'EUR', dividendType: 'coupon', isAutoGenerated: true,
      }, 'BTP', 'BTP Alfa', undefined, true);
    }
    expect(docIds).toEqual(['a1_2026-12-15_coupon', 'a1_2026-12-15_coupon']);
  });
});
