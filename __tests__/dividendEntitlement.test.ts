/**
 * What a dividend is owed on (lib/utils/dividendEntitlement.ts): the quantity the ledger held at the
 * end of the Italian day before the ex-date — the trade day for a share, the value date for a coupon.
 *
 * Every date sits at noon UTC (the same Italian day under any TZ), except U3's, which is an instant of
 * 23:30 UTC on purpose: in Italy it is already the next day. Figures are invented and round.
 */
import { describe, it, expect } from 'vitest';
import {
  canBeOwedSince,
  describeAnnouncedDividendsOutcome,
  entitledQuantity,
  entitlementBasisOf,
  quantityHeldBefore,
  reconcileAnnouncedDividend,
  settlementDayIso,
  type AnnouncedDividend,
} from '@/lib/utils/dividendEntitlement';
import type { AssetTransaction, AssetTransactionType } from '@/types/assetTransactions';

const noon = (iso: string) => new Date(`${iso}T12:00:00Z`);

let seq = 0;
function trade(type: AssetTransactionType, date: Date, quantity: number, extra: Partial<AssetTransaction> = {}): AssetTransaction {
  seq += 1;
  const createdAt = new Date(Date.UTC(2020, 0, 1));
  return {
    id: `t${seq}`, userId: 'u1', assetId: 'a1', type, date, quantity,
    pricePerUnit: 10, priceEur: 10, createdAt, updatedAt: createdAt, ...extra,
  };
}

function announced(overrides: Partial<AnnouncedDividend> = {}): AnnouncedDividend {
  return {
    isAutoGenerated: true,
    expenseId: undefined,
    dividendType: 'ordinary',
    exDate: noon('2026-03-15'),
    paymentDate: noon('2026-03-25'),
    quantity: 100,
    dividendPerShare: 0.5,
    grossAmount: 50,
    taxAmount: 13,
    ...overrides,
  };
}

describe('quantityHeldBefore', () => {
  // U1
  it('counts the trades of the days before the ex-date, a sale ON the ex-date not among them', () => {
    const trades = [trade('buy', noon('2026-03-01'), 100), trade('sell', noon('2026-03-10'), 40)];

    expect(quantityHeldBefore(trades, noon('2026-03-05'))).toBe(100);
    expect(quantityHeldBefore(trades, noon('2026-03-10'))).toBe(100);
    expect(quantityHeldBefore(trades, noon('2026-03-15'))).toBe(60);
  });

  // U2
  it('cannot say without trades, nor before a migration baseline; says 0 before a first real purchase', () => {
    expect(quantityHeldBefore([], noon('2026-03-10'))).toBeNull();
    expect(quantityHeldBefore([trade('buy', noon('2026-03-20'), 100, { isBaseline: true })], noon('2026-03-10'))).toBeNull();
    expect(quantityHeldBefore([trade('buy', noon('2026-03-20'), 100)], noon('2026-03-10'))).toBe(0);
  });

  // U3
  it('reads the trade on the Italian day: 23:30 UTC on the eve is already the ex-date in Italy', () => {
    const trades = [
      trade('buy', noon('2026-03-01'), 100),
      trade('buy', new Date('2026-03-09T23:30:00Z'), 50),
    ];

    expect(quantityHeldBefore(trades, noon('2026-03-10'))).toBe(100);
  });
});

describe('entitledQuantity and canBeOwedSince', () => {
  it('falls back to the asset quantity when the ledger cannot say, and takes the ledger otherwise', () => {
    expect(entitledQuantity(80, [], noon('2026-03-10'))).toBe(80);
    expect(entitledQuantity(80, [trade('buy', noon('2026-03-01'), 100)], noon('2026-03-10'))).toBe(100);
  });

  it('a sold-out instrument can be owed only when a trade falls inside the window', () => {
    const old = [trade('buy', noon('2026-01-01'), 100), trade('sell', noon('2026-01-05'), 100)];
    const recent = [...old, trade('buy', noon('2026-03-01'), 10), trade('sell', noon('2026-03-02'), 10)];

    expect(canBeOwedSince(5, [], noon('2026-02-01'))).toBe(true);
    expect(canBeOwedSince(0, old, noon('2026-02-01'))).toBe(false);
    expect(canBeOwedSince(0, recent, noon('2026-02-01'))).toBe(true);
  });
});

describe('reconcileAnnouncedDividend', () => {
  const ASOF = '2026-03-12';

  // U4
  it('rewrites a pending record on the quantity held, keeping its own tax share', () => {
    const trades = [trade('buy', noon('2026-03-01'), 100), trade('sell', noon('2026-03-10'), 40)];

    const at26 = reconcileAnnouncedDividend(announced(), trades, ASOF);
    const at125 = reconcileAnnouncedDividend(announced({ taxAmount: 6.25 }), trades, ASOF);

    expect(at26.kind).toBe('update');
    expect(at125.kind).toBe('update');
    if (at26.kind !== 'update' || at125.kind !== 'update') return;
    expect(at26.quantity).toBeCloseTo(60, 9);
    expect(at26.grossAmount).toBeCloseTo(30, 9);
    expect(at26.taxAmount).toBeCloseTo(7.8, 9);
    expect(at26.netAmount).toBeCloseTo(22.2, 9);
    expect(at125.quantity).toBeCloseTo(60, 9);
    expect(at125.grossAmount).toBeCloseTo(30, 9);
    expect(at125.taxAmount).toBeCloseTo(3.75, 9);
    expect(at125.netAmount).toBeCloseTo(26.25, 9);
  });

  // U5
  it('never touches a hand-entered record nor a cashed one', () => {
    const soldOut = [trade('buy', noon('2026-03-01'), 100), trade('sell', noon('2026-03-10'), 100)];

    expect(reconcileAnnouncedDividend(announced({ isAutoGenerated: false }), soldOut, ASOF)).toEqual({ kind: 'keep' });
    expect(reconcileAnnouncedDividend(announced({ expenseId: 'exp-1' }), soldOut, ASOF)).toEqual({ kind: 'keep' });
  });

  // U6
  it('deletes what was not held at the ex-date, keeps what a later sale leaves owed, and drops a record written at 0', () => {
    const soldBefore = [trade('buy', noon('2026-03-01'), 100), trade('sell', noon('2026-03-10'), 100)];
    const soldAfter = [trade('buy', noon('2026-03-01'), 100), trade('sell', noon('2026-03-20'), 100)];

    expect(reconcileAnnouncedDividend(announced(), soldBefore, ASOF)).toEqual({ kind: 'delete' });
    expect(reconcileAnnouncedDividend(announced(), soldAfter, ASOF)).toEqual({ kind: 'keep' });
    expect(reconcileAnnouncedDividend(announced({ quantity: 0, grossAmount: 0, taxAmount: 0 }), soldBefore, ASOF))
      .toEqual({ kind: 'delete' });
  });

  // U8
  it('leaves a record whose payment day has passed, and treats the payment day itself as still to be paid', () => {
    const soldBefore = [trade('buy', noon('2026-03-01'), 100), trade('sell', noon('2026-03-10'), 100)];

    expect(reconcileAnnouncedDividend(announced({ paymentDate: noon('2026-03-19') }), soldBefore, '2026-03-20'))
      .toEqual({ kind: 'keep' });
    expect(reconcileAnnouncedDividend(announced({ paymentDate: noon('2026-03-20') }), soldBefore, '2026-03-20'))
      .toEqual({ kind: 'delete' });
  });

  // U9
  it('reads a coupon on the value date, a share dividend on the trade day, a baseline on its own day', () => {
    expect(settlementDayIso('2026-03-05')).toBe('2026-03-09');
    expect(entitlementBasisOf('coupon')).toBe('settlement');
    expect(entitlementBasisOf('finalPremium')).toBe('settlement');
    expect(entitlementBasisOf('ordinary')).toBe('trade');

    // Thursday 5 March settles on Monday 9, Friday 6 March on Tuesday 10 — the coupon's own date.
    const buys = [trade('buy', noon('2026-03-05'), 1000), trade('buy', noon('2026-03-06'), 500)];
    const sameDates = { exDate: noon('2026-03-10'), paymentDate: noon('2026-03-10'), quantity: 1500, dividendPerShare: 0.02, grossAmount: 30, taxAmount: 3.75 };

    expect(quantityHeldBefore(buys, noon('2026-03-10'), 'settlement')).toBe(1000);
    const coupon = reconcileAnnouncedDividend(announced({ ...sameDates, dividendType: 'coupon' }), buys, '2026-03-09');
    expect(coupon.kind).toBe('update');
    if (coupon.kind === 'update') expect(coupon.quantity).toBe(1000);
    expect(reconcileAnnouncedDividend(announced({ ...sameDates, dividendType: 'ordinary' }), buys, '2026-03-09'))
      .toEqual({ kind: 'keep' });

    const baseline = [trade('buy', noon('2026-03-09'), 1000, { isBaseline: true })];
    expect(quantityHeldBefore(baseline, noon('2026-03-10'), 'settlement')).toBe(1000);
  });
});

describe('describeAnnouncedDividendsOutcome', () => {
  // U7
  it('says nothing when nothing moved, and names what was recomputed and what was removed', () => {
    expect(describeAnnouncedDividendsOutcome({ updated: 0, deleted: 0 })).toBeNull();
    expect(describeAnnouncedDividendsOutcome({ updated: 1, deleted: 0 }))
      .toBe('1 dividendo annunciato ricalcolato sulla quantità posseduta allo stacco.');
    expect(describeAnnouncedDividendsOutcome({ updated: 0, deleted: 2 }))
      .toBe('2 dividendi annunciati eliminati: allo stacco lo strumento non era in portafoglio.');
    expect(describeAnnouncedDividendsOutcome({ updated: 2, deleted: 1 }))
      .toBe('2 dividendi annunciati ricalcolati e 1 eliminato: conta la quantità posseduta allo stacco.');
  });
});
