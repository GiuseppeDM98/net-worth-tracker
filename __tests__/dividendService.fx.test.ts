/**
 * dividendService — a dividend in a foreign currency (2026-11-23): converted at the ECB rate of its
 * PAYMENT day or from the euro credited, two withholdings stored with `taxAmount` as their sum, a
 * refused credit rethrown untouched for the routes' 422, an edit that converts again only on a changed
 * figure, and the payment day's re-conversion of a record converted at another day's rate.
 *
 * The real service runs on an Admin Firestore mock that captures `add`, `set` and `update`; the ECB
 * rate (`resolveEcbRateToEur`) is mocked. Dates at noon; figures invented and round.
 * Seen red (2026-11-25) by: the ex-date passed for the payment day; the TradeFxError wrapped like the
 * others; a conversion whenever the update carries a currency; a record with no `fxSource` skipped.
 */
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { FieldValue } from 'firebase-admin/firestore';

vi.mock('server-only', () => ({}));

const { stored, writes, resolveEcbRateToEur } = vi.hoisted(() => ({
  stored: new Map<string, Record<string, unknown>>(),
  writes: [] as Array<{ op: 'add' | 'set' | 'update'; id: string; data: Record<string, unknown> }>,
  resolveEcbRateToEur: vi.fn(),
}));

vi.mock('@/lib/server/tradeFxService', () => ({ resolveEcbRateToEur }));

vi.mock('@/lib/firebase/admin', () => ({
  adminDb: {
    collection: () => ({
      add: async (data: Record<string, unknown>) => {
        writes.push({ op: 'add', id: 'new-id', data });
        return { id: 'new-id' };
      },
      doc: (id: string) => ({
        get: async () => ({ exists: stored.has(id), data: () => stored.get(id) }),
        set: async (data: Record<string, unknown>) => { writes.push({ op: 'set', id, data }); },
        update: async (data: Record<string, unknown>) => { writes.push({ op: 'update', id, data }); },
      }),
    }),
  },
}));

import { createDividend, reconvertAtPaymentDay, updateDividend } from '@/lib/services/dividendService';
import { TradeFxError } from '@/lib/utils/tradeFx';
import type { Dividend, DividendFormData } from '@/types/dividend';

const noon = (iso: string) => new Date(`${iso}T12:00:00Z`);
const EX_DATE = noon('2026-03-10');
const PAYMENT_DATE = noon('2026-03-25');
const DAY_RATE = { rate: 0.9, isLatest: false };

/** 10 units at 0,50 USD, 15% abroad and 26% in Italy on the frontier net. */
const USD_FORM: DividendFormData = {
  assetId: 'a1',
  exDate: EX_DATE,
  paymentDate: PAYMENT_DATE,
  dividendPerShare: 0.5,
  quantity: 10,
  grossAmount: 5,
  taxAmount: 0.75 + 1.105,
  netAmount: 5 - 0.75 - 1.105,
  foreignTaxAmount: 0.75,
  currency: 'USD',
  dividendType: 'ordinary',
  isAutoGenerated: false,
};

const lastWrite = () => writes[writes.length - 1].data;
const isDelete = (value: unknown) => value instanceof FieldValue && value.isEqual(FieldValue.delete());
const ts = (date: Date) => ({ toDate: () => date });

async function rejectionOf(promise: Promise<unknown>): Promise<unknown> {
  try {
    await promise;
  } catch (error) {
    return error;
  }
  throw new Error('expected a rejection');
}

function storedUsd(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    ...USD_FORM,
    exDate: ts(EX_DATE),
    paymentDate: ts(PAYMENT_DATE),
    grossAmountEur: 4.5, netAmountEur: 2.83, taxAmountEur: 1.67, foreignTaxAmountEur: 0.68,
    exchangeRate: 0.9, fxSource: 'ecb',
    ...overrides,
  };
}

function record(overrides: Partial<Dividend> = {}): Dividend {
  return {
    id: 'd1', userId: 'u1', assetTicker: 'ALFA', assetName: 'Azione Alfa',
    ...USD_FORM,
    createdAt: noon('2026-03-01'), updatedAt: noon('2026-03-01'),
    ...overrides,
  } as Dividend;
}

beforeEach(() => {
  stored.clear();
  writes.length = 0;
  resolveEcbRateToEur.mockReset();
  resolveEcbRateToEur.mockResolvedValue(DAY_RATE);
});

describe('createDividend — a foreign dividend (S1)', () => {
  it('should store the two withholdings with taxAmount as their sum and convert at the PAYMENT day’s rate', async () => {
    await createDividend('u1', USD_FORM, 'ALFA', 'Azione Alfa', 'US0000000001');

    expect(resolveEcbRateToEur).toHaveBeenCalledWith('USD', PAYMENT_DATE);
    const doc = lastWrite();
    expect(doc.taxAmount).toBeCloseTo((doc.foreignTaxAmount as number) + 1.105, 12);
    expect(doc.foreignTaxAmount).toBe(0.75);
    expect(doc.grossAmountEur).toBe(4.5);
    expect(doc.netAmountEur).toBe(2.83);
    expect(doc.taxAmountEur).toBe(1.67);
    expect(doc.foreignTaxAmountEur).toBe(0.68);
    expect(doc.exchangeRate).toBe(0.9);
    expect(doc.fxSource).toBe('ecb');
  });

  it('should mark a dividend paid on a later day as converted at the latest rate', async () => {
    resolveEcbRateToEur.mockResolvedValue({ rate: 0.9, isLatest: true });

    await createDividend('u1', USD_FORM, 'ALFA', 'Azione Alfa');

    expect(lastWrite().fxSource).toBe('ecb-latest');
  });

  it('should store the foreign part of a German share in euro, no euro field and no credit', async () => {
    await createDividend('u1', { ...USD_FORM, currency: 'EUR', settledNetEur: 3 }, 'BETA', 'Azione Beta', 'DE0000000004');

    const doc = lastWrite();
    expect(resolveEcbRateToEur).not.toHaveBeenCalled();
    expect(doc.foreignTaxAmount).toBe(0.75);
    for (const field of ['grossAmountEur', 'netAmountEur', 'taxAmountEur', 'foreignTaxAmountEur', 'exchangeRate', 'fxSource', 'settledNetEur']) {
      expect(doc).not.toHaveProperty(field);
    }
  });
});

describe('a refused credit and a missing rate (S2)', () => {
  const offBy30 = USD_FORM.netAmount * 0.9 * 1.3;

  it('should reject a credit 30% off with the TradeFxError itself, on a create and on an update', async () => {
    const created = await rejectionOf(createDividend('u1', { ...USD_FORM, settledNetEur: offBy30 }, 'ALFA', 'Azione Alfa'));
    stored.set('d1', storedUsd());
    const updated = await rejectionOf(updateDividend('d1', { settledNetEur: offBy30 }));

    for (const error of [created, updated]) {
      expect(error).toBeInstanceOf(TradeFxError);
      expect((error as TradeFxError).code).toBe('total-off');
      expect((error as TradeFxError).ecbRate).toBe(0.9);
    }
  });

  it('should save a record with no euro fields when no rate can be read', async () => {
    resolveEcbRateToEur.mockResolvedValue(null);

    await createDividend('u1', USD_FORM, 'ALFA', 'Azione Alfa');

    expect(lastWrite()).not.toHaveProperty('netAmountEur');
    expect(lastWrite()).not.toHaveProperty('fxSource');
    expect(lastWrite().grossAmount).toBe(5);
  });
});

describe('reconvertAtPaymentDay (S3)', () => {
  it('should return a record with a credit, one at the day’s rate and an EUR one as they are, unread', async () => {
    const cases = [
      record({ settledNetEur: 2.88, fxSource: 'statement' }),
      record({ fxSource: 'ecb' }),
      record({ currency: 'EUR' }),
    ];

    for (const dividend of cases) expect(await reconvertAtPaymentDay(dividend)).toBe(dividend);
    expect(resolveEcbRateToEur).not.toHaveBeenCalled();
    expect(writes).toHaveLength(0);
  });

  it('should convert again at the payment day’s rate a record at the latest rate and one saved with no source', async () => {
    resolveEcbRateToEur.mockResolvedValue({ rate: 0.95, isLatest: false });

    for (const dividend of [record({ fxSource: 'ecb-latest', exchangeRate: 0.9 }), record({ exchangeRate: 0.9 })]) {
      const result = await reconvertAtPaymentDay(dividend);
      expect(result.exchangeRate).toBe(0.95);
      expect(result.fxSource).toBe('ecb');
      expect(result.netAmountEur).toBe(2.99);
      expect(lastWrite().netAmountEur).toBe(2.99);
    }
    expect(resolveEcbRateToEur).toHaveBeenCalledWith('USD', PAYMENT_DATE);
  });

  it('should return the record unchanged when no rate can be read', async () => {
    resolveEcbRateToEur.mockResolvedValue(null);
    const dividend = record({ fxSource: 'ecb-latest' });

    expect(await reconvertAtPaymentDay(dividend)).toBe(dividend);
    expect(writes).toHaveLength(0);
  });
});

describe('updateDividend — converts again only on a changed figure (S3)', () => {
  it('should read no rate and write no euro field when only the note changed', async () => {
    stored.set('d1', storedUsd());

    await updateDividend('d1', { ...USD_FORM, notes: 'ornitorinco' });

    expect(resolveEcbRateToEur).not.toHaveBeenCalled();
    const doc = lastWrite();
    expect(doc.notes).toBe('ornitorinco');
    for (const field of ['grossAmountEur', 'netAmountEur', 'taxAmountEur', 'exchangeRate', 'fxSource']) {
      expect(doc).not.toHaveProperty(field);
    }
  });

  it('should delete a cleared credit and apply the ECB rate', async () => {
    stored.set('d1', storedUsd({ settledNetEur: 2.88, fxSource: 'statement', exchangeRate: 2.88 / USD_FORM.netAmount }));

    await updateDividend('d1', { ...USD_FORM, settledNetEur: null });

    const doc = lastWrite();
    expect(isDelete(doc.settledNetEur)).toBe(true);
    expect(doc.fxSource).toBe('ecb');
    expect(doc.exchangeRate).toBe(0.9);
    expect(doc.netAmountEur).toBe(2.83);
  });

  it('should delete the seven euro fields when the currency becomes EUR', async () => {
    stored.set('d1', storedUsd({ settledNetEur: 2.88 }));

    await updateDividend('d1', { ...USD_FORM, currency: 'EUR' });

    const doc = lastWrite();
    for (const field of ['grossAmountEur', 'taxAmountEur', 'netAmountEur', 'foreignTaxAmountEur', 'exchangeRate', 'fxSource', 'settledNetEur']) {
      expect(isDelete(doc[field])).toBe(true);
    }
    expect(doc.foreignTaxAmount).toBe(0.75);
    expect(resolveEcbRateToEur).not.toHaveBeenCalled();
  });

  it('should convert again at the payment day’s rate when the gross changed', async () => {
    stored.set('d1', storedUsd());

    await updateDividend('d1', { ...USD_FORM, grossAmount: 10, taxAmount: 3.71, netAmount: 6.29, foreignTaxAmount: 1.5 });

    expect(resolveEcbRateToEur).toHaveBeenCalledWith('USD', PAYMENT_DATE);
    expect(lastWrite().netAmountEur).toBe(5.66);
  });
});
