/**
 * DividendDialog on a foreign dividend (2026-11-23): the currency follows the instrument until the
 * owner picks one, every amount says its currency, a non-Italian issuer has two withholdings with
 * their proposals, «Netto accreditato in euro» previews the euro side with the ECB rate the hook
 * reads (mocked here: the network is never asserted), and an edit sends the foreign part and the
 * credit only when they mean something. Invented, round figures and invented ISINs.
 *
 * Seen red (2026-11-25, each turning one test red) by: the currency set on every pick, the owner's
 * choice ignored; two withholdings for every ISIN, an Italian one included; the «Cambio di oggi»
 * sentence dropped for a payment still to come; `foreignTaxAmount` always sent on an edit.
 */
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import type { Asset } from '@/types/assets';
import type { Dividend } from '@/types/dividend';

const { fetchMock, toastMock, fx, registry } = vi.hoisted(() => ({
  fetchMock: vi.fn(),
  toastMock: { success: vi.fn(), info: vi.fn(), warning: vi.fn(), error: vi.fn() },
  fx: { data: { rate: 0.9123, isLatest: false } as { rate: number; isLatest: boolean } | undefined, isLoading: false },
  registry: { assets: [] as Asset[] },
}));

vi.mock('@/lib/firebase/config', () => ({ auth: { currentUser: null }, db: {} }));
vi.mock('@/contexts/AuthContext', () => ({ useAuth: () => ({ user: { uid: 'owner-1' } }) }));
vi.mock('@/contexts/ActiveAccountContext', () => ({ useActiveAccount: () => ({ ownerId: 'owner-1' }) }));
vi.mock('@/lib/services/userPreferencesService', () => ({ getUserPreferences: vi.fn(async () => ({})), setUserPreferences: vi.fn() }));
vi.mock('sonner', () => ({ toast: toastMock }));
vi.mock('@/lib/hooks/useAssets', () => ({ useAssets: () => ({ data: registry.assets, isLoading: false, isError: false }) }));
vi.mock('@/lib/hooks/useFxRate', () => ({
  useFxRate: (currency: string | undefined) => (currency ? fx : { data: undefined, isLoading: false }),
}));
vi.mock('@/lib/utils/authFetch', () => ({ authenticatedFetch: fetchMock }));

import { DividendDialog } from '@/components/dividends/DividendDialog';

const at = (iso: string) => new Date(`${iso}T12:00:00Z`);
const asset = (fields: Partial<Asset>) =>
  ({
    userId: 'owner-1', type: 'stock', assetClass: 'equity', quantity: 10, currentPrice: 50, taxRate: 26,
    lastPriceUpdate: at('2026-11-10'), createdAt: at('2026-11-10'), updatedAt: at('2026-11-10'),
    ...fields,
  }) as unknown as Asset;

const ALFA = asset({ id: 'a-us', ticker: 'ALFA', name: 'Azione Alfa', currency: 'USD', isin: 'US0000000001' });
const BETA = asset({ id: 'a-de', ticker: 'BETA', name: 'Azione Beta', currency: 'EUR', isin: 'DE0000000002' });
const GAMMA = asset({ id: 'a-it', ticker: 'GAMMA', name: 'Azione Gamma', currency: 'EUR', isin: 'IT0000000003' });

const record = (fields: Partial<Dividend>) =>
  ({
    id: 'd-1', userId: 'owner-1', assetId: 'a-us', assetTicker: 'ALFA', assetName: 'Azione Alfa', assetIsin: 'US0000000001',
    exDate: at('2026-11-02'), paymentDate: at('2026-11-16'), dividendPerShare: 1, quantity: 10,
    grossAmount: 10, taxAmount: 2.6, netAmount: 7.4, currency: 'USD', dividendType: 'ordinary',
    isAutoGenerated: false, createdAt: at('2026-11-02'), updatedAt: at('2026-11-02'),
    ...fields,
  }) as unknown as Dividend;

function stubMatchMedia(matches: boolean) {
  vi.stubGlobal('matchMedia', (query: string) => ({
    matches, media: query, onchange: null,
    addEventListener: () => {}, removeEventListener: () => {}, addListener: () => {}, removeListener: () => {},
    dispatchEvent: () => false,
  }));
}

function renderDialog(props: { dividend?: Dividend; dividends?: Dividend[] } = {}) {
  return render(<DividendDialog open onClose={() => {}} dividend={props.dividend ?? null} dividends={props.dividends ?? []} />);
}

async function pickInstrument(name: string) {
  const input = document.getElementById('assetId') as HTMLInputElement;
  fireEvent.focus(input);
  fireEvent.change(input, { target: { value: name } });
  fireEvent.click(await screen.findByRole('button', { name: new RegExp(name) }));
}

const currencySelect = () => screen.findByRole('combobox', { name: /Valuta/ });

async function pickCurrency(code: string) {
  fireEvent.pointerDown(await currencySelect(), { button: 0, ctrlKey: false, pointerType: 'mouse' });
  const option = await screen.findByRole('option', { name: code });
  option.focus();
  fireEvent.keyDown(option, { key: 'Enter' });
  await waitFor(() => expect(screen.queryByRole('listbox')).toBeNull());
}

const field = (id: string) => document.getElementById(id) as HTMLInputElement;
const labelOf = (id: string) => normalize(document.querySelector(`label[for="${id}"]`)?.textContent ?? null);
const normalize = (text: string | null) => (text ?? '').replace(/\s/g, ' ');
const summary = () => normalize(screen.getByText('Riepilogo').parentElement!.textContent);

async function fillAlfa() {
  renderDialog();
  await pickInstrument('Azione Alfa');
  fireEvent.change(field('grossAmountPerShare'), { target: { value: '1' } });
  fireEvent.change(field('paymentDate'), { target: { value: '2026-11-16' } });
}

beforeEach(() => {
  vi.clearAllMocks();
  // A desktop: the modal is a dialog and the instrument picker a list under its field.
  stubMatchMedia(false);
  fx.data = { rate: 0.9123, isLatest: false };
  fx.isLoading = false;
  registry.assets = [ALFA, BETA, GAMMA];
  fetchMock.mockResolvedValue({ ok: true, status: 200, json: async () => ({}) });
  HTMLElement.prototype.hasPointerCapture ??= () => false;
  HTMLElement.prototype.releasePointerCapture ??= () => undefined;
  HTMLElement.prototype.scrollIntoView ??= () => undefined;
});

describe('DividendDialog — the currency follows the instrument', () => {
  it('sets USD on a dollar instrument, and the labels say it', async () => {
    renderDialog();
    await pickInstrument('Azione Alfa');
    await waitFor(async () => expect((await currencySelect()).textContent).toBe('USD'));
    expect(labelOf('grossAmountPerShare')).toBe('Importo lordo per unità (USD) *');
  });

  it('keeps the currency the owner picked when another instrument is chosen', async () => {
    renderDialog();
    await pickInstrument('Azione Alfa');
    await pickCurrency('CHF');
    await pickInstrument('Azione Gamma');
    await waitFor(() => expect(labelOf('withholdingTax')).toMatch(/\(CHF\)/));
    expect((await currencySelect()).textContent).toBe('CHF');
  });
});

describe('DividendDialog — two withholdings for a foreign issuer', () => {
  it('a US share in USD: both fields with their proposals, the summary in dollars with both rows', async () => {
    await fillAlfa();
    expect(labelOf('foreignWithholdingTax')).toBe('Ritenuta estera per unità (USD) *proposta al 15%');
    expect(labelOf('withholdingTax')).toBe('Ritenuta italiana per unità (USD) *proposta al 26%');
    await waitFor(() => expect(field('foreignWithholdingTax').value).toBe('0.15'));
    // (1 − 0,15) × 26% = 0,221.
    await waitFor(() => expect(field('withholdingTax').value).toBe('0.221'));
    const text = summary();
    expect(text).toContain('Ritenuta estera1,50 USD');
    expect(text).toContain('Ritenuta italiana2,21 USD');
    expect(text).not.toContain('Ritenute totali');
  });

  it('a German share in euro: two fields and no credited net', async () => {
    renderDialog();
    await pickInstrument('Azione Beta');
    await waitFor(() => expect(field('foreignWithholdingTax')).not.toBeNull());
    expect(labelOf('withholdingTax')).toMatch(/^Ritenuta italiana per unità \(€\)/);
    expect(field('settledNetEur')).toBeNull();
  });

  it('an Italian share: one field', async () => {
    renderDialog();
    await pickInstrument('Azione Gamma');
    await waitFor(() => expect(labelOf('withholdingTax')).toMatch(/^Ritenuta per unità \(€\) \*/));
    expect(field('foreignWithholdingTax')).toBeNull();
  });

  it('proposes the foreign rate of the instrument’s last record', async () => {
    const older = record({ id: 'd-old', paymentDate: at('2026-05-15'), grossAmount: 10, foreignTaxAmount: 3 });
    const last = record({ id: 'd-last', paymentDate: at('2026-08-15'), grossAmount: 10, foreignTaxAmount: 1 });
    renderDialog({ dividends: [older, last] });
    await pickInstrument('Azione Alfa');
    await waitFor(() => expect(labelOf('foreignWithholdingTax')).toMatch(/proposta al 10%$/));
  });
});

describe('DividendDialog — the euro side', () => {
  it('previews the ECB rate of the payment day', async () => {
    await fillAlfa();
    // Net 10 × (1 − 0,15 − 0,221) = 6,29 USD × 0,9123 = 5,74 €.
    const line = await screen.findByTestId('dividend-fx-line');
    expect(normalize(line.textContent)).toBe('Cambio BCE del 16/11/2026: EUR/USD 1,0961 · netto stimato 5,74 €');
  });

  it('reads the rate from a typed credit', async () => {
    await fillAlfa();
    fireEvent.change(field('settledNetEur'), { target: { value: '5.7' } });
    // 5,70 / 6,29 = 0,90620 → EUR/USD 1,1035.
    await waitFor(() => expect(normalize(screen.getByTestId('dividend-fx-line').textContent)).toBe('Cambio dal tuo accredito: EUR/USD 1,1035'));
  });

  it('says the rate is today’s for a payment still to come', async () => {
    await fillAlfa();
    fireEvent.change(field('paymentDate'), { target: { value: '2099-01-15' } });
    await waitFor(() =>
      expect(screen.getByTestId('dividend-fx-line').textContent).toBe('Cambio di oggi: quello del giorno di pagamento lo applico quando arriva.'),
    );
  });

  it('refuses a credit 30% off under the field and keeps the submit enabled', async () => {
    await fillAlfa();
    fireEvent.change(field('settledNetEur'), { target: { value: '4' } });
    expect(await screen.findByText(/Il totale in euro non torna con il cambio del giorno \(EUR\/USD 1,0961\)/)).toBeTruthy();
    expect((screen.getByRole('button', { name: 'Registra pagamento' }) as HTMLButtonElement).disabled).toBe(false);
  });
});

describe('DividendDialog — an edit sends what it means', () => {
  const sentUpdates = () => JSON.parse(fetchMock.mock.calls[0][1].body).updates;

  it('a record with no foreign part, its note changed: no foreignTaxAmount key', async () => {
    renderDialog({ dividend: record({}) });
    await waitFor(() => expect(field('foreignWithholdingTax').value).toBe('0'));
    fireEvent.change(field('notes'), { target: { value: 'corretta la nota' } });
    fireEvent.click(screen.getByRole('button', { name: 'Salva modifiche' }));
    await waitFor(() => expect(fetchMock).toHaveBeenCalledOnce());
    expect('foreignTaxAmount' in sentUpdates()).toBe(false);
    expect('settledNetEur' in sentUpdates()).toBe(false);
  });

  it('a stored credit cleared: settledNetEur null', async () => {
    renderDialog({ dividend: record({ settledNetEur: 6.8 }) });
    await waitFor(() => expect(field('settledNetEur').value).toBe('6.8'));
    fireEvent.change(field('settledNetEur'), { target: { value: '' } });
    fireEvent.click(screen.getByRole('button', { name: 'Salva modifiche' }));
    await waitFor(() => expect(fetchMock).toHaveBeenCalledOnce());
    expect(sentUpdates().settledNetEur).toBeNull();
  });

  it('a record with a foreign part opens on its two per-unit figures', async () => {
    renderDialog({ dividend: record({ foreignTaxAmount: 1.5, taxAmount: 3.71, netAmount: 6.29 }) });
    await waitFor(() => expect(field('foreignWithholdingTax').value).toBe('0.15'));
    expect(field('withholdingTax').value).toBe('0.221');
    expect(within(screen.getByText('Riepilogo').parentElement!).getByText('Ritenuta estera')).toBeTruthy();
  });
});

describe('DividendDialog — the dates left on today', () => {
  // A payment left on «today» is saved at the day's start, as a typed date is: with the clock of the
  // form's opening it was later than the tab's `now` and read as announced until a reload.
  it('are sent at the start of the day, never with the clock of the opening', async () => {
    renderDialog();
    await pickInstrument('Azione Gamma');
    fireEvent.change(field('grossAmountPerShare'), { target: { value: '1' } });
    await waitFor(() => expect(field('withholdingTax').value).toBe('0.26'));
    fireEvent.click(screen.getByRole('button', { name: 'Registra pagamento' }));
    await waitFor(() => expect(fetchMock).toHaveBeenCalledOnce());
    const { dividendData } = JSON.parse(fetchMock.mock.calls[0][1].body);
    const now = new Date();
    const dayStart = new Date(now.getFullYear(), now.getMonth(), now.getDate()).toISOString();
    expect(dividendData.paymentDate).toBe(dayStart);
    expect(dividendData.exDate).toBe(dayStart);
  });
});
