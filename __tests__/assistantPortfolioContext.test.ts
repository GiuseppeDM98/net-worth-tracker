function build(overrides: Partial<BuildPortfolioContextInput> = {}) {
  return buildAssistantPortfolioContext({
    assets: ASSETS,
    transactions: TRANSACTIONS,
    dividends: DIVIDENDS,
    pensionContributions: CONTRIBUTIONS,
    expenses: INSTALMENTS,
    targets: {
      equity: { targetPercentage: 60, subTargets: { 'All World': 100 } },
      bonds: { targetPercentage: 20 },
      cash: { targetPercentage: 0, useFixedAmount: true, fixedAmount: 10000 },
      carry: { targetPercentage: 0 },
    },
    goalAssignments: [
      { goalId: 'g1', assetId: 'a-etf', percentage: 50 },
      { goalId: 'g2', assetId: 'a-bond', units: 5000 },
    ],
    familyMembers: [GIUSEPPE, MARCELLA],
    ownerAge: 35,
    assetValueOf: valueOf,
    now: NOW,
    ...overrides,
  });
}

describe('buildAssistantPortfolioContext — holdings', () => {
  it('lists every held asset and every open loan, largest first, a sold-out position left out', () => {
    const { holdings } = build();
    expect(holdings.map((row) => row.name)).toEqual(['Casa', 'Fondo pensione', 'Conto corrente', 'ETF Mondo', 'BTP Esempio 2030', 'Mutuo casa']);
    expect(holdings.find((row) => row.name === 'ETF Venduto')).toBeUndefined();
  });

  it('resolves the role within the list: a mortgage follows the excluded home it finances', () => {
    const { holdings } = build();
    const roles = Object.fromEntries(holdings.map((row) => [row.name, row.role]));
    expect(roles).toEqual({
      Casa: 'excluded',
      'Mutuo casa': 'excluded',
      'Fondo pensione': 'frozen',
      'Conto corrente': 'tradable',
      'ETF Mondo': 'tradable',
      'BTP Esempio 2030': 'tradable',
    });
    expect(holdings.find((row) => row.name === 'Mutuo casa')).toMatchObject({ valueEur: -80000, financedAssetName: 'Casa' });
  });

  it('measures the G/P in euro against the fiscal PMC only where Patrimonio does', () => {
    const { holdings } = build();
    expect(holdings.find((row) => row.name === 'ETF Mondo')).toMatchObject({ costPerUnitEur: 100, costBasisEur: 10000, gainEur: 2000, gainPct: 20 });
    // An account and a pension fund have no PMC to measure against; the home is hand-valued.
    for (const name of ['Conto corrente', 'Fondo pensione', 'Casa']) {
      expect(holdings.find((row) => row.name === name)?.gainEur).toBeUndefined();
    }
  });

  it('names the owner through the ownership rule and keeps the ticker only when it says more than the name', () => {
    const { holdings } = build();
    expect(holdings.find((row) => row.name === 'ETF Mondo')).toMatchObject({ ticker: 'MONDO.MI', owner: 'di Giuseppe' });
    expect(holdings.find((row) => row.name === 'Fondo pensione')).toMatchObject({ owner: 'di Marcella', isLiquid: false });
    expect(holdings.find((row) => row.name === 'Conto corrente')).toMatchObject({ owner: null, isLiquid: true });
    expect(holdings.find((row) => row.name === 'Conto corrente')?.ticker).toBeUndefined();
  });

  it('carries the raw ticker for the profile cache on a quoted holding and the maturity on a bond, for the Consulente\'s bond block (2026-11-08)', () => {
    const { holdings } = build();
    expect(holdings.find((row) => row.name === 'ETF Mondo')?.profileTicker).toBe('MONDO.MI');
    expect(holdings.find((row) => row.name === 'ETF Mondo')?.maturityIso).toBeUndefined();
    expect(holdings.find((row) => row.name === 'BTP Esempio 2030')).toMatchObject({ maturityIso: '2030-03-01' });
    expect(holdings.find((row) => row.name === 'BTP Esempio 2030')?.profileTicker).toBeUndefined();
    expect(holdings.find((row) => row.name === 'Conto corrente')?.profileTicker).toBeUndefined();
  });
});

describe('buildAssistantPortfolioContext — the goals\' hold on each holding', () => {
  it('says what share of a holding the goals take and the euro left free, FIRE › Obiettivi\'s arithmetic', () => {
    const { holdings, goalCoverage } = build();
    expect(holdings.find((row) => row.name === 'ETF Mondo')).toMatchObject({ goalAssignedPct: 50, goalFreeEur: 6000 });
    expect(holdings.find((row) => row.name === 'BTP Esempio 2030')).toMatchObject({ goalAssignedPct: 100, goalFreeEur: 0 });
    expect(holdings.find((row) => row.name === 'Conto corrente')).toMatchObject({ goalAssignedPct: 0, goalFreeEur: 20000 });
    // A loan is no holding a goal can take.
    expect(holdings.find((row) => row.name === 'Mutuo casa')?.goalFreeEur).toBeUndefined();
    // The home counts net of its mortgage (200000 − 80000), the loan not at all.
    expect(holdings.find((row) => row.name === 'Casa')).toMatchObject({ goalAssignedPct: 0, goalValueEur: 120000, goalFreeEur: 120000 });
    // Σ over what the goals can hold: 12000 + 5000 + 20000 + 30000 + 120000.
    expect(goalCoverage).toEqual({ totalEur: 187000, assignedEur: 11000, freeEur: 176000 });
  });

  it('carries nothing of the goals when the feature is off — a feature not in use, never a zero', () => {
    const { holdings, goalCoverage } = build({ goalAssignments: null });
    expect(holdings.every((row) => row.goalAssignedPct === undefined && row.goalFreeEur === undefined)).toBe(true);
    expect(goalCoverage).toBeNull();
  });
});

describe('buildAssistantPortfolioContext — allocation on the page\'s base', () => {
  it('sums the base as tradable + frozen and nets the mortgage off the excluded home', () => {
    const { allocation } = build();
    expect(allocation.tradableTotal).toBe(12000 + 5000 + 20000);
    expect(allocation.frozenTotal).toBe(30000);
    expect(allocation.baseTotal).toBe(67000);
    expect(allocation.excludedTotal).toBe(200000 - 80000);
    expect(allocation.excluded.map((row) => row.name)).toEqual(['Casa', 'Mutuo casa']);
    expect(allocation.frozen.map((row) => row.name)).toEqual(['Fondo pensione']);
  });

  it('reads each class on the base, the frozen share named, the sub-categories under it', () => {
    const { allocation } = build();
    const equity = allocation.byClass.find((row) => row.assetClass === 'equity');
    expect(equity).toMatchObject({ value: 42000, frozenValue: 30000, tradableValue: 12000 });
    expect(equity?.pct).toBeCloseTo((42000 / 67000) * 100, 6);
    expect(equity?.subCategories.map((sub) => sub.subCategory)).toEqual(['Fondo Pensione', 'All World']);
    // No real estate on the base: the home and its loan are out.
    expect(allocation.byClass.find((row) => row.assetClass === 'realestate')).toBeUndefined();
  });

  it('carves a fixed cash amount out of the base before the other targets apply, like the page', () => {
    const { allocation } = build();
    const targets = allocation.targets ?? [];
    const cash = targets.find((row) => row.assetClass === 'cash');
    expect(cash).toMatchObject({ fixedAmount: 10000, currentValue: 20000 });
    expect(cash?.targetPct).toBeCloseTo((10000 / 67000) * 100, 6);
    // Equity: 60% of (67000 − 10000) = 34200 → 51.04% of the base.
    const equity = targets.find((row) => row.assetClass === 'equity');
    expect(equity?.targetPct).toBeCloseTo((34200 / 67000) * 100, 6);
    expect(equity?.gapPp).toBeCloseTo(((42000 - 34200) / 67000) * 100, 6);
    // A class with a 0% target and no fixed amount is not a row.
    expect(targets.find((row) => row.assetClass === 'carry')).toBeUndefined();
  });

  it('lists the targeted sleeves of a class and the sleeve the targets do not name', () => {
    const { allocation } = build();
    const equity = allocation.targets?.find((row) => row.assetClass === 'equity');
    expect(equity?.subRows.map((sub) => sub.subCategory)).toEqual(['All World', 'Fondo Pensione']);
    const allWorld = equity?.subRows.find((sub) => sub.subCategory === 'All World');
    expect(allWorld?.currentPctOfClass).toBeCloseTo((12000 / 42000) * 100, 6);
    expect(allWorld?.targetPctOfClass).toBe(100);
    const untargeted = equity?.subRows.find((sub) => sub.subCategory === 'Fondo Pensione');
    expect(untargeted?.targetPctOfClass).toBe(0);
  });

  it('answers null targets when none are configured', () => {
    expect(build({ targets: null }).allocation.targets).toBeNull();
  });
});

describe('buildAssistantPortfolioContext — ledger and registers', () => {
  it('orders the ledger by date, names the asset or says it is gone, carries fees and the baseline flag', () => {
    const { ledger } = build();
    expect(ledger.totalRows).toBe(3);
    expect(ledger.omittedRows).toBe(0);
    expect(ledger.rows.map((row) => row.dateIso)).toEqual(['2025-05-05', '2026-01-10', '2026-09-10']);
    expect(ledger.rows[0]).toMatchObject({ assetName: 'Strumento non più in portafoglio', type: 'buy' });
    expect(ledger.rows[1]).toMatchObject({ assetName: 'ETF Mondo', ticker: 'MONDO.MI', isBaseline: true, amountEur: 12000, feesEur: 0 });
    expect(ledger.rows[2]).toMatchObject({ type: 'sell', quantity: 20, priceEur: 118, feesEur: 2, amountEur: 2360 });
  });

  it('keeps the most recent rows when the ledger exceeds the cap and counts what it left out', () => {
    const many: AssetTransaction[] = [];
    for (let i = 0; i < PORTFOLIO_LEDGER_ROW_CAP + 7; i += 1) {
      many.push(transaction({ id: `t-${i}`, assetId: 'a-etf', type: 'buy', date: new Date(Date.UTC(2020, 0, 1) + i * 86_400_000), quantity: 1, priceEur: 100 }));
    }
    const { ledger } = build({ transactions: many });
    expect(ledger.totalRows).toBe(PORTFOLIO_LEDGER_ROW_CAP + 7);
    expect(ledger.omittedRows).toBe(7);
    expect(ledger.rows).toHaveLength(PORTFOLIO_LEDGER_ROW_CAP);
    expect(ledger.rows[0].dateIso).toBe('2020-01-08');
  });

  it('splits the dividend registry at today — received and announced never one figure — in euro', () => {
    const { dividends } = build();
    expect(dividends.received.map((row) => row.paymentDateIso)).toEqual(['2026-03-01', '2026-09-01']);
    expect(dividends.announced.map((row) => row.paymentDateIso)).toEqual(['2027-03-01']);
    expect(dividends.announced[0]).toMatchObject({ isProvisional: true, netEur: 65.63 });
    // A USD dividend reads its EUR conversion.
    expect(dividends.received[0]).toMatchObject({ assetName: 'ETF Mondo', grossEur: 46, netEur: 34 });
    expect(dividends.omittedReceived).toBe(0);
  });

  it('states the coupon of every bond held: rate, frequency, maturity', () => {
    const { dividends } = build();
    expect(dividends.coupons).toHaveLength(1);
    expect(dividends.coupons[0]).toMatchObject({ assetName: 'BTP Esempio 2030', annualRatePct: 3, frequency: 'semestrale', maturityIso: '2030-03-01', indexation: null });
    expect(dividends.coupons[0].nextCouponIso).not.toBeNull();
  });
});

