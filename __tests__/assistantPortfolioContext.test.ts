function valueOf(a: Asset): number {
  const base = a.quantity * a.currentPrice;
  return a.type === 'loan' ? -base || 0 : base;
}

function transaction(overrides: Partial<AssetTransaction> & Pick<AssetTransaction, 'id' | 'assetId' | 'type' | 'date' | 'quantity' | 'priceEur'>): AssetTransaction {
  return { userId: 'u1', pricePerUnit: overrides.priceEur, createdAt: NOW, updatedAt: NOW, ...overrides };
}

