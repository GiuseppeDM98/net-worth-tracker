/**
 * POST /api/dividends and PUT /api/dividends/[dividendId] — a refused credit is a 422 with its
 * sentence, never the generic 500 (2026-11-23); the POST also refuses a currency the instrument does
 * not have and the list does not hold. The service is mocked to reject as the real one does.
 * Seen red (2026-11-25) by: the catch removed from either route (the error falls to the 500).
 */
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { NextRequest } from 'next/server';

vi.mock('server-only', () => ({}));

vi.mock('@/lib/server/apiAuth', () => ({
  requireFirebaseAuth: vi.fn(async () => ({ uid: 'user-1' })),
  assertCanAccessAccount: vi.fn(async () => undefined),
  getApiAuthErrorResponse: vi.fn(() => null),
}));

const { assetData, createDividendMock, updateDividendMock, getDividendByIdMock } = vi.hoisted(() => ({
  assetData: { current: {} as Record<string, unknown> },
  createDividendMock: vi.fn(),
  updateDividendMock: vi.fn(),
  getDividendByIdMock: vi.fn(),
}));

vi.mock('@/lib/firebase/admin', () => ({
  adminDb: {
    collection: vi.fn(() => ({
      doc: vi.fn((id: string) => ({ get: vi.fn(async () => ({ exists: true, id, data: () => assetData.current })) })),
    })),
  },
}));

vi.mock('@/lib/services/dividendService', () => ({
  createDividend: createDividendMock,
  updateDividend: updateDividendMock,
  getDividendById: getDividendByIdMock,
  deleteDividend: vi.fn(),
  deleteUpcomingCouponsForAsset: vi.fn(),
  deleteUpcomingFinalPremiumForAsset: vi.fn(),
  isDuplicateDividend: vi.fn(async () => false),
  getAllDividends: vi.fn(),
  getDividendsByAsset: vi.fn(),
  getDividendsByDateRange: vi.fn(),
}));

vi.mock('@/lib/services/dividendIncomeService', () => ({
  createExpenseFromDividend: vi.fn(),
  updateExpenseFromDividend: vi.fn(),
  deleteExpenseForDividend: vi.fn(),
}));

import { POST } from '@/app/api/dividends/route';
import { PUT } from '@/app/api/dividends/[dividendId]/route';
import { TradeFxError, describeTotalOff } from '@/lib/utils/tradeFx';

const DIVIDEND_DATA = {
  assetId: 'a1',
  exDate: '2026-03-10T12:00:00.000Z',
  paymentDate: '2026-03-25T12:00:00.000Z',
  dividendPerShare: 0.5,
  quantity: 10,
  grossAmount: 5,
  taxAmount: 1.855,
  netAmount: 3.145,
  foreignTaxAmount: 0.75,
  settledNetEur: 3.7,
  currency: 'USD',
  dividendType: 'ordinary',
  isAutoGenerated: false,
};

function request(url: string, method: string, body: unknown): NextRequest {
  return new NextRequest(url, {
    method,
    headers: { 'content-type': 'application/json', authorization: 'Bearer token' },
    body: JSON.stringify(body),
  });
}

const post = (dividendData: Record<string, unknown> = DIVIDEND_DATA) =>
  POST(request('http://localhost/api/dividends', 'POST', { userId: 'user-1', dividendData }));
const put = (updates: Record<string, unknown> = DIVIDEND_DATA) =>
  PUT(request('http://localhost/api/dividends/d1', 'PUT', { updates }), { params: Promise.resolve({ dividendId: 'd1' }) });

beforeEach(() => {
  vi.clearAllMocks();
  assetData.current = { userId: 'user-1', ticker: 'ALFA', name: 'Azione Alfa', currency: 'USD', averageCost: 10 };
  getDividendByIdMock.mockResolvedValue({ id: 'd1', userId: 'user-1', currency: 'USD' });
});

describe('the dividend routes — a refused credit (R1)', () => {
  it('should answer the POST with 422 and the sentence of the day’s rate', async () => {
    createDividendMock.mockRejectedValue(new TradeFxError('total-off', 0.9));

    const response = await post();

    expect(response.status).toBe(422);
    expect((await response.json()).error).toBe(describeTotalOff('USD', 0.9));
  });

  it('should answer the PUT with 422 and the same sentence', async () => {
    updateDividendMock.mockRejectedValue(new TradeFxError('total-off', 0.9));

    const response = await put();

    expect(response.status).toBe(422);
    expect((await response.json()).error).toBe(describeTotalOff('USD', 0.9));
  });

  it('should answer a credit on a net of zero with 422 and its own sentence', async () => {
    createDividendMock.mockRejectedValue(new TradeFxError('nothing-to-convert'));
    updateDividendMock.mockRejectedValue(new TradeFxError('nothing-to-convert'));

    for (const response of [await post(), await put()]) {
      expect(response.status).toBe(422);
      expect((await response.json()).error).toBe('Il netto accreditato in euro richiede un netto maggiore di zero.');
    }
  });

  it('should refuse on the POST a currency the instrument does not have and the list does not hold', async () => {
    const response = await post({ ...DIVIDEND_DATA, currency: 'ZAR' });

    expect(response.status).toBe(400);
    expect((await response.json()).error).toBe('Valuta non ammessa per questo strumento.');
    expect(createDividendMock).not.toHaveBeenCalled();
  });

  it('should accept null on the PUT to remove the two optional amounts', async () => {
    updateDividendMock.mockResolvedValue(undefined);

    const response = await put({ foreignTaxAmount: null, settledNetEur: null, notes: 'fenicottero' });

    expect(response.status).toBe(200);
    expect(updateDividendMock).toHaveBeenCalledWith('d1', { foreignTaxAmount: null, settledNetEur: null, notes: 'fenicottero' });
  });
});
