/**
 * Each worker its own universe — the wiring, checked from inside a worker.
 *
 * The whole run gives every worker a Firestore project, a server and a set of parked sessions
 * (e2e/emulator.ts). Three things carry a test into the right one, and each fails quietly: Playwright
 * reloading `playwright.config.ts` inside the worker process (where `baseURL` is computed from the
 * worker's index), the page picking its project from the port it is served on
 * (lib/firebase/emulatorProject.ts), and that port's server reading the same project with the Admin
 * SDK. If one stopped holding, two workers would write the same documents and the reds would be
 * intermittent and far from the cause; this file says it by name instead.
 *
 * With one worker (an area run) every expectation reads the base project and port 3100, and holds
 * — so the falsifications below are seen on the whole run's servers, in a worker other than 0.
 *
 * Seen red there on 2026-11-26, four copies side by side (`--fully-parallel --repeat-each=4`):
 * `workerIndexOfPort` returning 0 (the page asked for the base project on :3101–3103, 3 red) and
 * every server's `--firestore-project` naming the base project (the route did not return the row
 * planted in `-w1`, `-w2`, `-w3`: 4 red); 13 green with both put back.
 */
import { test, expect } from '@playwright/test';
import { BASE_URL, FIRESTORE_DOCUMENTS, PROJECT_ID, WORKER_INDEX, baseUrlOf } from './emulator';

const OWNER = { Authorization: 'Bearer owner', 'Content-Type': 'application/json' };
const UID = 'test-user-1';
const COUPON_ID = 'e2e-isolation-coupon';
/** The note names the project it was planted in: another project's copy could not pass for it. */
const DECOY_NOTE = `cedola tapiro ${PROJECT_ID}`;

async function removeCoupon(): Promise<void> {
  await fetch(`${FIRESTORE_DOCUMENTS}/dividends/${COUPON_ID}`, { method: 'DELETE', headers: OWNER });
  expect((await fetch(`${FIRESTORE_DOCUMENTS}/dividends/${COUPON_ID}`, { headers: OWNER })).status).toBe(404);
}

test('the config this worker loaded is this worker’s: its index, its server', async ({ baseURL }, testInfo) => {
  expect(WORKER_INDEX).toBe(testInfo.parallelIndex);
  expect(baseURL).toBe(baseUrlOf(testInfo.parallelIndex));
  expect(baseURL).toBe(BASE_URL);
});

test('the page reads this worker’s Firestore project, and no other', async ({ page }) => {
  const databases = new Set<string>();
  page.on('request', (request) => {
    const database = new URL(request.url()).searchParams.get('database');
    if (database) databases.add(database);
  });

  await page.goto('/dashboard/cashflow');
  await expect(page.getByRole('region', { name: /^Verdetto/ }).first()).toBeVisible({ timeout: 45_000 });

  // The Web SDK names its database on every channel request: `projects/<id>/databases/(default)`.
  await expect.poll(() => [...databases]).toEqual([`projects/${PROJECT_ID}/databases/(default)`]);
});

test('this worker’s server reads the same project: a coupon planted here comes back from its route', async ({ page }) => {
  const paid = new Date();
  paid.setDate(paid.getDate() - 20);
  const paidIso = paid.toISOString();
  await removeCoupon();
  try {
    const planted = await fetch(`${FIRESTORE_DOCUMENTS}/dividends/${COUPON_ID}`, {
      method: 'PATCH',
      headers: OWNER,
      body: JSON.stringify({
        fields: {
          userId: { stringValue: UID },
          assetId: { stringValue: 'seed-btp' },
          assetTicker: { stringValue: 'BTP' },
          assetName: { stringValue: 'BTP Valore 2030' },
          exDate: { timestampValue: paidIso },
          paymentDate: { timestampValue: paidIso },
          dividendPerShare: { doubleValue: 6.5 },
          quantity: { doubleValue: 5 },
          grossAmount: { doubleValue: 32.5 },
          taxAmount: { doubleValue: 4.0625 },
          netAmount: { doubleValue: 28.4375 },
          currency: { stringValue: 'EUR' },
          dividendType: { stringValue: 'coupon' },
          notes: { stringValue: DECOY_NOTE },
          isAutoGenerated: { booleanValue: false },
          createdAt: { timestampValue: paidIso },
          updatedAt: { timestampValue: paidIso },
        },
      }),
    });
    expect(planted.ok).toBe(true);

    // Asked of the SERVER: the stats route reads the registry with the Admin SDK, and the page's
    // own request carries the token — the answer is read off the wire, not off the screen.
    const answered = page.waitForResponse((response) => response.url().includes('/api/dividends/stats') && response.ok(), {
      timeout: 45_000,
    });
    await page.goto('/dashboard/cashflow?tab=dividends');
    const body = (await (await answered).json()) as { dividends?: Array<{ notes?: string }> };
    expect(body.dividends?.map((dividend) => dividend.notes)).toContain(DECOY_NOTE);
  } finally {
    await removeCoupon();
  }
});
